"""Input sharing orchestration around Deskflow / Input Leap.

GOLEM LINK does not re-implement low-level keyboard/mouse interception. It
detects a proven KVM tool, generates its configuration from the node layout and
hands the operator exact start/install commands. The two machines stay
independent operating systems.
"""

from __future__ import annotations

import os
import shutil
from pathlib import Path

import psutil

from ..config import ConfigManager, InputSharingConfig

WINDOWS_CANDIDATES = [
    r"C:\Program Files\Deskflow\deskflow.exe",
    r"C:\Program Files\Deskflow\deskflow-server.exe",
    r"C:\Program Files\Deskflow\deskflow-client.exe",
    r"C:\Program Files\InputLeap\input-leap.exe",
    r"C:\Program Files\Barrier\barrier.exe",
]
LINUX_BINARIES = [
    "deskflow",
    "deskflow-server",
    "deskflow-client",
    "input-leap",
    "input-leaps",
    "barrier",
    "barriers",
]


def _sanitize_screen(name: str) -> str:
    cleaned = "".join(ch if ch.isalnum() or ch in "-_." else "-" for ch in name.strip())
    return cleaned or "screen"


class InputSharingManager:
    def __init__(self, cfg: ConfigManager) -> None:
        self.cfg = cfg
        self.config_dir = cfg.data_dir / "input-sharing"

    # -- detection ---------------------------------------------------------
    def detect(self) -> dict:
        binaries: list[str] = []
        for candidate in WINDOWS_CANDIDATES:
            if os.path.exists(candidate):
                binaries.append(candidate)
        for name in LINUX_BINARIES:
            path = shutil.which(name)
            if path:
                binaries.append(path)
        processes = []
        for proc in psutil.process_iter(["name", "pid"]):
            try:
                name = (proc.info.get("name") or "").lower()
            except (psutil.NoSuchProcess, psutil.AccessDenied):
                continue
            if any(k in name for k in ("deskflow", "input-leap", "barrier")):
                processes.append({"pid": proc.info["pid"], "name": proc.info["name"]})
        tool = "none"
        if binaries:
            joined = " ".join(binaries).lower()
            if "deskflow" in joined:
                tool = "deskflow"
            elif "input-leap" in joined:
                tool = "input-leap"
        return {
            "installed": bool(binaries),
            "tool": tool,
            "binaries": binaries,
            "running": processes,
            "platform": os.name,
            "notes": self._platform_notes(),
        }

    @staticmethod
    def _platform_notes() -> list[str]:
        notes = [
            "Deskflow/Input Leap must run inside the logged-in desktop session, not as the background service.",
            "Clipboard sharing is provided by the KVM tool and works between Windows and Linux text clipboards.",
        ]
        if os.name != "nt":
            notes.append(
                "On Wayland, input injection needs a compositor that supports virtual input (e.g. KDE with uinput) — "
                "GNOME Wayland limits remote input; an X11 session is the reliable choice."
            )
        else:
            notes.append(
                "Windows may need the KVM tool installed as a service/startup app and allowed through the firewall on Private networks."
            )
        return notes

    # -- configuration -----------------------------------------------------
    def screen_names(self) -> list[str]:
        cfg = self.cfg.get()
        screens = cfg.input_sharing.screens
        if screens:
            return [_sanitize_screen(s.name or s.node_id) for s in screens]
        return [_sanitize_screen(cfg.node_name)]

    def generate(self) -> dict:
        cfg = self.cfg.get()
        layout = cfg.input_sharing
        screens = layout.screens
        if len(screens) < 2:
            raise ValueError("configure at least two screens with left/right sides first")
        ids = [s.node_id for s in screens]
        if len(set(ids)) != len(ids):
            raise ValueError("each screen must have a distinct node id")
        if layout.server_node_id and layout.server_node_id not in ids:
            raise ValueError("server node is not part of the screen layout")
        left = next((s for s in screens if s.side == "left"), screens[0])
        right = next((s for s in screens if s.side == "right"), screens[-1])
        left_name = _sanitize_screen(left.name)
        right_name = _sanitize_screen(right.name)
        lines = [
            "# Generated by GOLEM LINK - Deskflow/Input Leap server configuration",
            "section: screens",
            f"    {left_name}:",
            f"        width = {left.width}",
            f"        height = {left.height}",
            f"    {right_name}:",
            f"        width = {right.width}",
            f"        height = {right.height}",
            "end",
            "",
            "section: links",
            f"    {left_name}:",
            f"        right = {right_name}",
            f"    {right_name}:",
            f"        left = {left_name}",
            "end",
            "",
            "section: options",
            f"    clipboardSharing = {'true' if layout.clipboard_sharing else 'false'}",
            "    screenSaverSync = true",
            "    relativeMouseMoves = false",
            "    heartbeat = 5000",
            f"    # keys: switch back to {left_name} with Ctrl+Alt+1",
            f"    keystroke(control+alt+1) = switchToScreen({left_name})",
            f"    keystroke(control+alt+2) = switchToScreen({right_name})",
            "end",
            "",
        ]
        self.config_dir.mkdir(parents=True, exist_ok=True)
        server_conf = self.config_dir / "deskflow-server.conf"
        server_conf.write_text("\n".join(lines), encoding="utf-8")

        server_id = layout.server_node_id
        server_screen = next((s for s in screens if s.node_id == server_id), screens[0])
        client_screen = next(s for s in screens if s.node_id != server_screen.node_id)
        server_host = _sanitize_screen(server_screen.name)
        client_host = _sanitize_screen(client_screen.name)
        auto = layout.auto_reconnect
        conf = str(server_conf)

        def loop_sh(command: str, label: str) -> str:
            if not auto:
                return f"{command}\n"
            return (
                "while true; do\n"
                f"    {command}\n"
                f'    echo "{label} exited; restarting in 3 s (auto-reconnect). Ctrl+C to stop."\n'
                "    sleep 3\n"
                "done\n"
            )

        server_cmd = (
            f'deskflow-server --config "{conf}" --name "{server_host}" || '
            f'input-leap-server --config "{conf}" --name "{server_host}"'
        )
        client_cmd = (
            f'deskflow-client --name "{client_host}" "$SERVER" || '
            f'input-leap-client --name "{client_host}" "$SERVER"'
        )
        header = "#!/usr/bin/env bash\n# Generated by GOLEM LINK - run in your logged-in desktop session\n"
        (self.config_dir / "start-server.sh").write_text(
            header + f"set -u\n{loop_sh(server_cmd, 'input sharing')}",
            encoding="utf-8",
            newline="\n",
        )
        (self.config_dir / "start-client.sh").write_text(
            header
            + f'# Usage: ./start-client.sh [server-host]  (default: {server_host}.local)\n'
            + f'SERVER="${{1:-{server_host}.local}}"\n'
            + loop_sh(client_cmd, "input sharing"),
            encoding="utf-8",
            newline="\n",
        )

        def loop_ps1(command: str, label: str) -> str:
            if not auto:
                return f"{command}\n"
            return (
                "while ($true) {\n"
                f"  {command}\n"
                f'  Write-Host "{label} exited; restarting in 3 s (auto-reconnect). Ctrl+C to stop."\n'
                "  Start-Sleep -Seconds 3\n"
                "}\n"
            )

        server_ps = (
            '& "C:\\Program Files\\Deskflow\\deskflow-server.exe" '
            f'--config "{conf}" --name "{server_host}"'
        )
        client_ps = (
            '& "C:\\Program Files\\Deskflow\\deskflow-client.exe" '
            f'--name "{client_host}" $Server'
        )
        ps_header = "# Generated by GOLEM LINK - run in your logged-in desktop session\n"
        (self.config_dir / "start-server.ps1").write_text(
            ps_header + loop_ps1(server_ps, "input sharing"), encoding="utf-8", newline="\r\n"
        )
        (self.config_dir / "start-client.ps1").write_text(
            ps_header
            + f'param([string]$Server = "{server_host}.local")\n'
            + loop_ps1(client_ps, "input sharing"),
            encoding="utf-8",
            newline="\r\n",
        )
        return {
            "server_config_path": str(server_conf),
            "server_screen": server_host,
            "client_screen": client_host,
            "auto_reconnect": auto,
            "screens": [s.model_dump() for s in screens],
            "scripts": {
                "linux_server": str(self.config_dir / "start-server.sh"),
                "linux_client": str(self.config_dir / "start-client.sh"),
                "windows_server": str(self.config_dir / "start-server.ps1"),
                "windows_client": str(self.config_dir / "start-client.ps1"),
            },
            "instructions": [
                f"On {server_screen.name}: run start-server.sh (Linux) or start-server.ps1 (Windows)",
                f"On {client_screen.name}: run start-client.sh <server-host> or start-client.ps1 <server-host>",
                "Left/right screen edges switch the shared keyboard and mouse as configured",
                "Auto-reconnect restarts the KVM tool after sleep, logout or a crash"
                if auto
                else "Auto-reconnect is off: the KVM tool stays stopped if it exits",
            ],
            "detected": self.detect(),
        }

    def status(self) -> dict:
        cfg = self.cfg.get()
        return {
            "enabled": cfg.input_sharing.enabled,
            "tool": cfg.input_sharing.tool,
            "screens": [s.model_dump() for s in cfg.input_sharing.screens],
            "server_node_id": cfg.input_sharing.server_node_id,
            "detected": self.detect(),
            "config_dir": str(self.config_dir),
        }

    def save_layout(self, layout: InputSharingConfig) -> dict:
        def mutate(cfg):
            cfg.input_sharing = layout

        self.cfg.update(mutate)
        return self.status()
