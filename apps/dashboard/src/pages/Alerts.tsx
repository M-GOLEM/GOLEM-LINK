import { AlertTriangle, BellOff, CheckCheck, Filter, ShieldAlert } from "lucide-react";
import { useEffect, useMemo, useState } from "react";
import {
  fmtClock,
  get,
  post,
  timeAgo,
  type Alert,
  type Cluster,
} from "../api";
import { Empty, Panel, Spinner, StatusDot, verdictTone } from "../components/ui";
import { usePolling } from "../hooks";
import { useApp } from "../store";

const CATEGORIES = ["cpu", "ram", "temperature", "disk", "network"];

export function AlertsPage() {
  const { me, toast, refresh } = useApp();
  const [openOnly, setOpenOnly] = useState(true);
  const [severity, setSeverity] = useState<"all" | Alert["severity"]>("all");
  const [category, setCategory] = useState("all");
  const [busy, setBusy] = useState<string | null>(null);
  const canWrite = me?.role === "admin";

  const alertsQ = usePolling(
    () => get<{ alerts: Alert[] }>(`/api/alerts?open_only=${openOnly}&limit=300`),
    5000,
  );
  const clusterQ = usePolling(() => get<Cluster>("/api/cluster"), 15000);
  const { reload } = alertsQ;

  useEffect(() => {
    void reload();
  }, [openOnly, reload]);

  const names = useMemo(() => {
    const map = new Map<string, string>();
    if (clusterQ.data) {
      map.set(clusterQ.data.local.node_id, `${clusterQ.data.local.name} (this node)`);
      for (const peer of clusterQ.data.peers) map.set(peer.node_id, peer.name);
    }
    return map;
  }, [clusterQ.data]);

  const categoryOptions = useMemo(() => {
    const seen = new Set(CATEGORIES);
    for (const alert of alertsQ.data?.alerts ?? []) seen.add(alert.category);
    return Array.from(seen).sort();
  }, [alertsQ.data]);

  const alerts = alertsQ.data?.alerts ?? [];
  const visible = alerts.filter(
    (alert) =>
      (severity === "all" || alert.severity === severity) &&
      (category === "all" || alert.category === category),
  );
  const openCount = alerts.filter((alert) => !alert.acknowledged).length;
  const criticalOpen = alerts.filter((alert) => !alert.acknowledged && alert.severity === "critical").length;
  const warningOpen = alerts.filter((alert) => !alert.acknowledged && alert.severity === "warning").length;

  const acknowledge = async (alert: Alert) => {
    setBusy(`ack-${alert.id}`);
    try {
      await post(`/api/alerts/${alert.id}/ack`);
      toast("Alert acknowledged", "ok");
      await reload();
      refresh();
    } catch (err) {
      toast(err instanceof Error ? err.message : "could not acknowledge alert", "error");
    } finally {
      setBusy(null);
    }
  };

  const acknowledgeAll = async () => {
    if (!openCount) return;
    setBusy("ack-all");
    try {
      await post("/api/alerts/ack-all");
      toast(`Acknowledged ${openCount} alert${openCount === 1 ? "" : "s"}`, "ok");
      await reload();
      refresh();
    } catch (err) {
      toast(err instanceof Error ? err.message : "could not acknowledge alerts", "error");
    } finally {
      setBusy(null);
    }
  };

  return (
    <div className="space-y-4">
      {alertsQ.error && (
        <div className="rounded-xl border border-rose-400/30 bg-rose-500/10 px-4 py-3 text-sm text-rose-200">
          Cannot load alerts: {alertsQ.error}
        </div>
      )}

      <div className="grid-cards">
        <div className="panel p-4">
          <div className="label">Open alerts</div>
          <div className="value mt-2">{openOnly ? alerts.length : openCount}</div>
          <p className="mt-2 text-[11px] text-slate-500">
            {openOnly ? "Showing unacknowledged alerts only." : "Unacknowledged in the loaded window."}
          </p>
        </div>
        <div className="panel p-4">
          <div className="label">Critical</div>
          <div className={`value mt-2 ${criticalOpen ? "text-rose-300" : ""}`}>{criticalOpen}</div>
          <p className="mt-2 text-[11px] text-slate-500">CPU/RAM limit exceeded, thermal protection or disk space critical.</p>
        </div>
        <div className="panel p-4">
          <div className="label">Warning</div>
          <div className={`value mt-2 ${warningOpen ? "text-amber-300" : ""}`}>{warningOpen}</div>
          <p className="mt-2 text-[11px] text-slate-500">Approaching a configured threshold.</p>
        </div>
        <div className="panel p-4">
          <div className="label">Loaded history</div>
          <div className="value mt-2">{alerts.length}</div>
          <p className="mt-2 text-[11px] text-slate-500">Most recent {alerts.length} records from the local SQLite store.</p>
        </div>
      </div>

      <Panel
        title={
          <div className="section-title">
            <ShieldAlert size={13} className="text-cyan-400" /> Alert stream
          </div>
        }
        subtitle="Generated by the local overload engine from real telemetry. Nothing here is simulated."
        actions={
          <>
            <button
              className={openOnly ? "btn-primary btn-xs" : "btn-ghost btn-xs"}
              onClick={() => setOpenOnly((value) => !value)}
            >
              <Filter size={12} /> {openOnly ? "Open only" : "All history"}
            </button>
            <button
              className="btn-ghost btn-xs"
              disabled={!canWrite || !openCount || busy === "ack-all"}
              onClick={() => void acknowledgeAll()}
              title={canWrite ? "Acknowledge every open alert" : "Viewer accounts cannot acknowledge"}
            >
              <CheckCheck size={12} /> Acknowledge all
            </button>
          </>
        }
        bodyClassName="p-0"
      >
        <div className="flex flex-wrap items-center gap-2 border-b border-ink-700/60 px-4 py-2.5">
          <span className="label mr-1">Severity</span>
          {(["all", "critical", "warning", "info"] as const).map((level) => (
            <button
              key={level}
              onClick={() => setSeverity(level)}
              className={`rounded-full border px-2.5 py-0.5 text-[11px] font-medium capitalize transition ${
                severity === level
                  ? "border-cyan-400/50 bg-cyan-400/10 text-cyan-200"
                  : "border-ink-600/70 bg-ink-900/50 text-slate-400 hover:text-slate-200"
              }`}
            >
              {level}
            </button>
          ))}
          <span className="label ml-3 mr-1">Category</span>
          <select
            className="select w-auto py-1 text-xs"
            value={category}
            onChange={(event) => setCategory(event.target.value)}
          >
            <option value="all">All categories</option>
            {categoryOptions.map((item) => (
              <option key={item} value={item}>
                {item}
              </option>
            ))}
          </select>
          <span className="ml-auto text-[11px] text-slate-600">
            {visible.length} shown{visible.length !== alerts.length ? ` of ${alerts.length}` : ""}
          </span>
        </div>

        {alertsQ.loading && !alertsQ.data ? (
          <div className="p-4">
            <Spinner label="Reading alert history…" />
          </div>
        ) : visible.length ? (
          <div className="overflow-x-auto">
            <table className="w-full min-w-[840px] border-collapse">
              <thead>
                <tr className="border-b border-ink-700/60">
                  <th className="th">Severity</th>
                  <th className="th">Alert</th>
                  <th className="th">Category</th>
                  <th className="th">Node</th>
                  <th className="th">Value</th>
                  <th className="th">Time</th>
                  <th className="th text-right">Action</th>
                </tr>
              </thead>
              <tbody>
                {visible.map((alert) => (
                  <tr key={alert.id} className="row-hover border-b border-ink-700/40 last:border-0">
                    <td className="td">
                      <span className={verdictTone(alert.severity)}>
                        <StatusDot state={alert.severity} /> {alert.severity}
                      </span>
                    </td>
                    <td className="td max-w-[320px]">
                      <div className="text-sm text-slate-200">{alert.message}</div>
                      {alert.acknowledged ? (
                        <div className="mt-0.5 text-[10px] text-slate-600">
                          acknowledged {timeAgo(alert.acknowledged_at)}
                        </div>
                      ) : null}
                    </td>
                    <td className="td">
                      <span className="badge-idle capitalize">{alert.category}</span>
                    </td>
                    <td className="td text-[11px] text-slate-400">{names.get(alert.node_id) ?? alert.node_id}</td>
                    <td className="td font-mono text-[11px] text-slate-400">
                      {alert.value != null ? alert.value.toFixed(1) : "—"}
                      {alert.threshold != null ? <span className="text-slate-600"> / {alert.threshold.toFixed(0)}</span> : null}
                    </td>
                    <td className="td text-[11px] text-slate-500" title={fmtClock(alert.ts)}>
                      {timeAgo(alert.ts)}
                    </td>
                    <td className="td text-right">
                      {alert.acknowledged ? (
                        <span className="text-[11px] text-slate-600">acknowledged</span>
                      ) : (
                        <button
                          className="btn-ghost btn-xs"
                          disabled={!canWrite || busy === `ack-${alert.id}`}
                          onClick={() => void acknowledge(alert)}
                        >
                          Acknowledge
                        </button>
                      )}
                    </td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        ) : (
          <div className="p-4">
            <Empty
              icon={openOnly ? BellOff : AlertTriangle}
              title={openOnly ? "No open alerts" : "No alerts match the filters"}
              hint={
                openOnly
                  ? "The overload engine will raise alerts when CPU, RAM, temperature, disk or latency cross the configured thresholds."
                  : "Switch back to open alerts or clear the severity/category filters."
              }
            />
          </div>
        )}
      </Panel>

      <p className="text-[11px] leading-relaxed text-slate-600">
        Thresholds live in Settings → Overload thresholds. Temperature alerts only fire for sensors the hardware actually
        reports, and this agent never kills processes to relieve load.
      </p>
    </div>
  );
}
